#define MEM_MAP_PART_STORAGE_A_OFFSET 0x00410000U
#define MEM_MAP_PART_STORAGE_SIZE     0x005F8000U          /* ~5.97MB（双槽各占一半） */
#define MEM_MAP_PART_STORAGE_B_OFFSET 0x00A08000U

#endif /* MEM_MAP_H */
